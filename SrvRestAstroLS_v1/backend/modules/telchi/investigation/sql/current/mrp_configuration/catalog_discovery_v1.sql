-- TELCHI MRP CONFIGURATION AUDIT V1
-- Gate 1: candidate SAP B1/HANA objects. SELECT-only; field meanings are
-- validated by the runner from SYS.TABLE_COLUMNS before extraction.
SELECT TABLE_NAME, 'TABLE' AS OBJECT_TYPE
FROM SYS.TABLES
WHERE SCHEMA_NAME = ?
  AND (
    TABLE_NAME IN ('OITM', 'OITW', 'OITB', 'OWHS', 'OCRD', 'OADM', 'OITT', 'ITT1', 'OFCT', 'FCT1', 'OINV', 'INV1', 'OPOR', 'POR1', 'OWOR', 'OINM')
    OR UPPER(TABLE_NAME) LIKE '%MRP%'
    OR UPPER(TABLE_NAME) LIKE '%FORECAST%'
    OR UPPER(TABLE_NAME) LIKE '%PLANN%'
    OR UPPER(TABLE_NAME) LIKE '%FCT%'
  )
UNION ALL
SELECT VIEW_NAME, 'VIEW' AS OBJECT_TYPE
FROM SYS.VIEWS
WHERE SCHEMA_NAME = ?
  AND (
    VIEW_NAME IN ('OITM', 'OITW', 'OITB', 'OWHS', 'OCRD', 'OADM', 'OITT', 'ITT1', 'OFCT', 'FCT1', 'OINV', 'INV1', 'OPOR', 'POR1', 'OWOR', 'OINM')
    OR UPPER(VIEW_NAME) LIKE '%MRP%'
    OR UPPER(VIEW_NAME) LIKE '%FORECAST%'
    OR UPPER(VIEW_NAME) LIKE '%PLANN%'
    OR UPPER(VIEW_NAME) LIKE '%FCT%'
  )
ORDER BY 1;
