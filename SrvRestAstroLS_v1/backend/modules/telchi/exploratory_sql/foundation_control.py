"""Local-only control runner. Never calls Luna or connects channels.

python -m modules.telchi.exploratory_sql.foundation_control --output NEW.json
Results are controller-generated control SQL, NOT SQL generated by Luna.
"""
import argparse
from dataclasses import asdict
from datetime import datetime, timezone
import fcntl
import json
import os
from pathlib import Path
import resource
import tempfile
import time

from .foundation import FoundationReadonlyExecutor, local_context
from .foundation_verifier import control_proposals, verify_control
from .research import code_digest
from .validator import validate


def control():
    context = local_context('TELCHIAI_EXPLORATORY_FOUNDATION_READONLY_V1')
    report = dict(identifier=context.investigation_id, timestamp=datetime.now(timezone.utc).isoformat(),
        code_digest=code_digest(), question='¿Cuánto vendimos de Calenta en agosto de 2026?',
        scope='Four reference SKUs, commercial lines, August 2026; local control only',
        sql_author='controller, NOT Luna', publication=context.publication, snapshot=context.snapshot,
        catalog=asdict(context.catalog), queries=[], business_data_sent_to_model=False,
        egress=dict(status='BLOCKED', endpoint='https://api.openai.com/v1/responses',
            model='gpt-5.6-luna', reasoning='medium', store=False,
            project_organization='Not explicitly selected by existing adapter; key-bound destination unaccredited',
            policy='No applicable enterprise data treatment attestation located; store=false is not an attestation',
            existing_approval='DEV commercial capability approval does not attest provider destination or exploratory observation egress'),
        states=dict(FOUNDATION_BINDING='PARTIAL', READONLY_EXECUTION='NOT_RUN',
            OPENAI_DATA_EGRESS='BLOCKED', LUNA_REAL_RESEARCH='BLOCKED', CALENTA_RECONCILIATION='NOT_RUN',
            INDEPENDENT_VERIFICATION='NOT_RUN', SECURITY_REGRESSION='NOT_RUN', TELCHI_V1_REGRESSION='NOT_RUN',
            WHATSAPP_E2E='NOT_RUN', READY_FOR_SHARED_SERVICE='BLOCKED'))
    started, results = time.monotonic(), []
    with FoundationReadonlyExecutor(context) as executor:
        for proposal in control_proposals():
            _, query = validate(proposal, context)
            decision, result = executor.execute(proposal, context)
            report['queries'].append(dict(proposal=asdict(proposal), validated=asdict(query) if query else None,
                decision=asdict(decision), result=asdict(result)))
            report['host_preflight'] = executor.last_preflight
            if result.status != 'COMPLETED':
                report['blocked_reason'] = decision.reason
                report['states']['READONLY_EXECUTION'] = 'BLOCKED'
                break
            results.append(result)
        if len(results) == 3:
            verification_start = time.monotonic()
            report['verification'] = verify_control(context, results)
            report['verification_seconds'] = time.monotonic() - verification_start
            report['states']['READONLY_EXECUTION'] = 'PASS'
            report['states']['FOUNDATION_BINDING'] = 'PASS'
            report['states']['INDEPENDENT_VERIFICATION'] = 'PARTIAL'
            # Existing commercial capability comparison is still a separate gate.
            report['states']['CALENTA_RECONCILIATION'] = 'PARTIAL'
        report['resources'] = dict(elapsed_seconds=time.monotonic()-started,
            peak_process_rss_kib=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
            duckdb_threads=1, duckdb_memory_limit_bytes=context.effective_budget.process_memory_bytes,
            sql_seconds=sum(r.elapsed_seconds for r in results), queries_attempted=len(report['queries']),
            queries_completed=len(results), model_calls=0, retries=0,
            os_isolation_accredited=False, connection_setup_deadline_enforced=False,
            process_memory_cpu_scan_bytes_enforced=False)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    lock_path = Path(tempfile.gettempdir()) / f'telchi-exploratory-dev-{os.getuid()}.lock'
    fd = os.open(lock_path, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, 'w') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise SystemExit('dev_investigation_busy') from None
        fd = os.open(output, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, 'w') as evidence:
            json.dump(control(), evidence, indent=2, ensure_ascii=False, default=str)
            evidence.write('\n')
    print(str(output))


if __name__ == '__main__':
    main()
